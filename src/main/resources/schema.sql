-- PostgreSQL

CREATE TABLE IF NOT EXISTS rooms (
    number integer PRIMARY KEY,
    max_persons integer NOT NULL,
    class TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS clients (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name TEXT NOT NULL,
    last_name TEXT NOT NULL,
    phone_number TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS reservations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id integer NOT NULL REFERENCES clients(id) ON DELETE SET NULL,
    room_number integer NOT NULL REFERENCES rooms(number) ON DELETE CASCADE,
    first_day date NOT NULL DEFAULT CURRENT_DATE,
    last_day date NOT NULL
);
